"""Export the mark geometry and the outlined words for the Remotion project (brand/motion/src/geometry.ts).
usage: python export_motion.py ../motion/src/geometry.ts
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hero as H

FIGTREE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fonts", "Figtree[wght].ttf")


def cmds(c):
    return [[k[0], *[list(p) for p in k[1:]]] for k in c]


word = H.word("ebloom", 1000)            # y-down, baseline 0, font units
desc = H.word("Plant doctor", 1000, wght=600, font=FIGTREE, close=0)
data = {
    "body": cmds(H.BODY), "vein": cmds(H.VEIN), "lower": cmds(H.LOWER),
    "tip": list(H.TIP), "stemL": H.STEM_L, "stemR": H.STEM_R, "xHeight": H.XH, "rAdvance": H.R_ADV,
    "word": [{"ch": g["ch"], "x": g["x"], "d": g["d"]} for g in word["glyphs"]], "wordWidth": word["width"],
    "desc": desc["d"], "descWidth": desc["width"],
}
with open(sys.argv[1], "w", encoding="utf-8") as fh:
    fh.write("// Generated by brand/source/export_motion.py — do not edit by hand.\n"
             "// Mark commands are in Bricolage font units, y-up, baseline 0. Words are y-down, baseline 0.\n"
             f"export const G = {json.dumps(data)} as const;\n")
print("wrote", sys.argv[1])
